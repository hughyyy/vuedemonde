#!/usr/bin/env node
/**
 * Regenerates `playground/src/catalogue/index.ts` from the demo SFCs on disk.
 *
 * The registry is generated rather than hand-maintained so it cannot drift from
 * the 106 exported components: `test/catalogue-registry.test.ts` asserts the
 * registry matches the barrels, and this script is what makes that cheap to
 * satisfy when a component is added.
 *
 * Group + width metadata lives in `catalogue-meta.json` (hand-edited, one row
 * per component) because those are editorial choices, not derivable facts.
 *
 * Usage: node scripts/catalogue-registry.mjs
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const DIR = join(ROOT, "playground", "src", "catalogue");
const META = join(DIR, "catalogue-meta.json");
const OUT = join(DIR, "index.ts");

/** Barrels whose default exports must all appear in the catalogue. */
const BARRELS = ["src/kit/index.ts", "src/charts/index.ts", "src/calendar/index.ts", "src/board/index.ts"];

const exported = BARRELS.flatMap((file) =>
  [...readFileSync(join(ROOT, file), "utf8").matchAll(/export \{ default as (\w+) \} from "\.\/[\w]+\.vue"/g)].map(
    (m) => m[1],
  ),
);

const meta = JSON.parse(readFileSync(META, "utf8"));
const demos = new Set(readdirSync(DIR).filter((f) => f.endsWith(".demo.vue")).map((f) => f.replace(".demo.vue", "")));

const missingDemo = exported.filter((n) => !demos.has(n));
const missingMeta = exported.filter((n) => !(n in meta));
if (missingDemo.length) console.warn(`! no demo SFC for: ${missingDemo.join(", ")}`);
if (missingMeta.length) console.warn(`! no catalogue-meta entry for: ${missingMeta.join(", ")}`);

const entries = exported
  .filter((n) => demos.has(n) && n in meta)
  .map((n) => ({ id: n, ...meta[n] }));

const groupOrder = ["primitives", "inputs", "overlays", "navigation", "data", "layout", "charts", "calendar", "board"];
entries.sort((a, b) => groupOrder.indexOf(a.group) - groupOrder.indexOf(b.group) || a.id.localeCompare(b.id));

const imports = entries.map((e) => `import ${e.id} from "./${e.id}.demo.vue";`).join("\n");
const rows = entries
  .map((e) => {
    const bits = [`label: ${JSON.stringify(e.id)}`, `group: ${JSON.stringify(e.group)}`, `demo: ${e.id}`];
    if (e.wide) bits.push("wide: true");
    if (typeof e.shot === "number") bits.push(`shot: ${e.shot}`);
    return `  ${e.id}: { ${bits.join(", ")} },`;
  })
  .join("\n");

const file = `/**
 * Catalogue registry — one demo per exported component.
 *
 * GENERATED by \`node scripts/catalogue-registry.mjs\` from the demo SFCs on disk
 * plus \`catalogue-meta.json\` (group/width editorial metadata). Do not hand-edit:
 * add the demo file and its meta row, then re-run the script.
 *
 * Contract (see docs/per-component-rendering.md):
 *   - covers EVERY \`export { default as X }\` in the four barrels;
 *     \`test/catalogue-registry.test.ts\` fails otherwise, so a new component
 *     cannot silently miss the catalogue.
 *   - \`group\` is the browser/README grouping, not the render order.
 *   - \`wide\` demos render at 780 px instead of the 520 px default; \`shot\`
 *     overrides the capture width outright.
 *
 * Demo SFC contract: a demo may declare \`defineProps<{ print?: boolean }>()\` and
 * use it to open overlay/service states that only exist in a static render.
 */
import type { Component } from "vue";
${imports}

/** Catalogue grouping — this order drives the sidebar and README sections. */
export const CATALOGUE_GROUPS = [
${groupOrder.map((g) => `  ${JSON.stringify(g)},`).join("\n")}
] as const;

export type CatalogueGroup = (typeof CATALOGUE_GROUPS)[number];

/** Default capture width, in CSS px, for one theme cell. */
export const SHOT_WIDTH = 520;

export type CatalogueEntry = {
  /** The exported component name, verbatim (\`AppButton\`, \`BarChart\`, …). */
  label: string;
  group: CatalogueGroup;
  demo: Component;
  /** Rendered at 1.5× width — tables, boards, editors, splitters. */
  wide?: boolean;
  /** Explicit capture width override (CSS px). */
  shot?: number;
};

export const COMPONENT_DEMOS: Record<string, CatalogueEntry> = {
${rows}
};
`;

if (!existsSync(META)) {
  console.error(`✗ ${META} missing`);
  process.exit(1);
}
writeFileSync(OUT, file);
console.log(`✓ registry: ${entries.length} components (${entries.length - missingDemo.length + missingDemo.length} exported)`);
if (missingDemo.length || missingMeta.length) {
  console.log(`  ${missingDemo.length} missing demo(s), ${missingMeta.length} missing meta row(s) — registry only includes complete entries`);
}
